/**
 * Regenerates src/js/core/blocksData.ts from the vendored Unicode
 * Blocks.txt (PLAN §3.4 charset tables): the block names and ranges
 * behind the charset picker. Committed output, like eawData.ts; it
 * only changes on a Unicode version bump. Runs under bun:
 *
 *   bun tools/genUnicodeBlocks.js
 *
 * Refresh procedure lives in assets/ucd/README.md.
 */

import { createHash } from 'node:crypto';
import { gunzipSync } from 'node:zlib';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const UCD_VERSION = '18.0.0';
const SHA256 = '77cdc7792ec3c34fda801d6aa38e98c8cbdd1b6db2421afbf0962a30c2318144';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(
	root,
	'assets',
	'ucd',
	`Blocks-${UCD_VERSION}.txt.gz`,
);
const outPath = path.join(root, 'src', 'js', 'core', 'blocksData.ts');

const raw = readFileSync(sourcePath);
const digest = createHash('sha256').update(raw).digest('hex');
if (digest !== SHA256) {
	console.error(`[blocks] ${path.basename(sourcePath)} sha256 mismatch:`);
	console.error(`  pinned ${SHA256}`);
	console.error(`  actual ${digest}`);
	process.exit(1);
}

const rows = [];
for (const line of gunzipSync(raw).toString('utf8').split('\n')) {
	const match = (/^([0-9A-F]+)\.\.([0-9A-F]+);\s*(.+?)\s*$/).exec(line);
	if (match) {
		rows.push(
			`\t[0x${match[1].toLowerCase()}, 0x${match[2].toLowerCase()}, ${JSON.stringify(match[3])}],`,
		);
	}
}

writeFileSync(
	outPath,
	`// GENERATED by tools/genUnicodeBlocks.js from
// assets/ucd/Blocks-${UCD_VERSION}.txt.gz — DO NOT EDIT BY HAND.
// [first codepoint, last codepoint, block name] per Unicode block.

export const BLOCKS_VERSION = '${UCD_VERSION}';

// prettier-ignore
export const UNICODE_BLOCKS: ReadonlyArray<readonly [number, number, string]> = [
${rows.join('\n')}
];
`,
);
console.log(`[blocks] wrote ${rows.length} blocks to src/js/core/blocksData.ts`);
