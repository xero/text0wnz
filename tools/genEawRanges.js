/**
 * Regenerates src/js/core/eawData.ts from the vendored Unicode East
 * Asian Width table (PLAN §3.4 width policy). Unlike the hex fonts,
 * the output is COMMITTED: it is ~130 ranges of TypeScript that tsc,
 * vitest, and the bundler all need statically, and it only changes on
 * a Unicode version bump. Runs under bun:
 *
 *   bun tools/genEawRanges.js
 *
 * Refresh procedure lives in assets/ucd/README.md.
 */

import { createHash } from 'node:crypto';
import { gunzipSync } from 'node:zlib';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const UCD_VERSION = '18.0.0';
const SHA256 = '600abcae8f6164ded54ee855a243e1ff3b8b08b4370723e587596fbce9f5eb36';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(
	root,
	'assets',
	'ucd',
	`EastAsianWidth-${UCD_VERSION}.txt.gz`,
);
const outPath = path.join(root, 'src', 'js', 'core', 'eawData.ts');

const raw = readFileSync(sourcePath);
const digest = createHash('sha256').update(raw).digest('hex');
if (digest !== SHA256) {
	console.error(`[eaw] ${path.basename(sourcePath)} sha256 mismatch:`);
	console.error(`  pinned ${SHA256}`);
	console.error(`  actual ${digest}`);
	process.exit(1);
}

const ranges = [];
for (const line of gunzipSync(raw).toString('utf8').split('\n')) {
	const match = (/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)/).exec(line);
	if (!match) {
		continue;
	}
	// W = Wide, F = Fullwidth: the two properties that occupy two cells
	if (match[3] === 'W' || match[3] === 'F') {
		ranges.push([parseInt(match[1], 16), parseInt(match[2] ?? match[1], 16)]);
	}
}
ranges.sort((a, b) => a[0] - b[0]);
const merged = [];
for (const [start, end] of ranges) {
	const last = merged[merged.length - 1];
	if (last && start <= last[1] + 1) {
		last[1] = Math.max(last[1], end);
	} else {
		merged.push([start, end]);
	}
}

const pairs = merged
	.map(([start, end]) => `\t0x${start.toString(16)}, 0x${end.toString(16)},`)
	.join('\n');
writeFileSync(
	outPath,
	`// GENERATED by tools/genEawRanges.js from
// assets/ucd/EastAsianWidth-${UCD_VERSION}.txt.gz — DO NOT EDIT BY HAND.
// Inclusive [start, end] pairs, flattened, of every codepoint whose
// East Asian Width is W (Wide) or F (Fullwidth).

export const EAW_VERSION = '${UCD_VERSION}';

// prettier-ignore
export const WIDE_RANGES: readonly number[] = [
${pairs}
];
`,
);
console.log(`[eaw] wrote ${merged.length} ranges to src/js/core/eawData.ts`);
